// Command opsgen writes the operation table the API uses to authorise requests:
// the permission, public flag and restricted flag of each operation in the
// spec. Run from api/ through `make gen`.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

const (
	specPath = "openapi.yaml"
	outPath  = "internal/http/apigen/operations.gen.go"
)

type operation struct {
	OperationID string      `yaml:"operationId"`
	Summary     string      `yaml:"summary"`
	Tags        []string    `yaml:"tags"`
	Permission  string      `yaml:"x-permission"`
	Restricted  bool        `yaml:"x-restricted"`
	Security    *[]struct{} `yaml:"security"`
	method      string
	path        string
}

type document struct {
	Paths map[string]map[string]yaml.Node `yaml:"paths"`
}

func main() {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}
	var doc document
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}

	var ops []operation
	for path, item := range doc.Paths {
		for method, node := range item {
			switch method {
			case "get", "post", "put", "patch", "delete":
				var op operation
				if err := node.Decode(&op); err != nil {
					log.Fatal(err)
				}
				op.method, op.path = strings.ToUpper(method), path
				ops = append(ops, op)
			}
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].OperationID < ops[j].OperationID })

	var b bytes.Buffer
	b.WriteString("// Code generated by codegen/opsgen. DO NOT EDIT.\n\npackage apigen\n\n")
	b.WriteString("// Operation is what the server needs to authorise one API operation.\n")
	b.WriteString("type Operation struct {\n\tPermission string\n\tSummary string\n\tModule string\n\tMethod string\n\tPath string\n\tPublic bool\n\tRestricted bool\n}\n\n")
	b.WriteString("// Operations is keyed by the Go operation name, as strict middleware sees it.\n")
	b.WriteString("var Operations = map[string]Operation{\n")
	for _, op := range ops {
		public := op.Security != nil && len(*op.Security) == 0
		module := ""
		if len(op.Tags) > 0 {
			module = op.Tags[0]
		}
		fmt.Fprintf(&b, "%q: {Permission: %q, Summary: %q, Module: %q, Method: %q, Path: %q, Public: %t, Restricted: %t},\n",
			upperFirst(op.OperationID), op.Permission, op.Summary, module, op.method, op.path, public, op.Restricted)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(outPath, out, 0o600); err != nil {
		log.Fatal(err)
	}
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return strings.Clone(string(r))
}
